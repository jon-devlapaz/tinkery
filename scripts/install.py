#!/usr/bin/env python3
"""Install or update Tinkery for the current user: the one supported install path.

Promises: builds this checkout (`cargo +stable build --locked --release`), or takes `--binary`,
and refuses to install a build whose `--snapshot` fails. Puts it at
~/.local/share/tinkery/bin/tinkery and keeps the build it replaces as tinkery.previous.
Writes the ~/.local/bin/tinkery launcher with the binary's absolute path, so the launcher
works under any HOME, and keeps a launcher it did not write as launcher.previous.
Checks the launcher the way scripts/first-task-check.py does, then prints what it installed.
Safe to run again. Runs no model, downloads only what cargo needs, and writes nothing else.
"""
import argparse
import hashlib
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile

REPO = Path(__file__).resolve().parents[1]
# first-task-check.py looks for this line to tell this launcher from a hand-written one.
MARKER = '# Written by tinkery scripts/install.py. To update, run it again; do not edit this file.'


class Refusal(Exception):
    pass


def launcher_text(binary):
    return f'#!/bin/sh\n{MARKER}\nexec {shlex.quote(str(binary))} --home "$@"\n'


def snapshot(program):
    """Run `program --snapshot` in a throwaway HOME, as the readiness check does."""
    with tempfile.TemporaryDirectory(prefix='tinkery-install-check-') as home:
        try:
            result = subprocess.run([str(program), '--snapshot', '--no-color'], env={**os.environ, 'HOME': home},
                                    capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.TimeoutExpired) as error:
            raise Refusal(f'{program} did not start: {error}') from error
    if result.returncode:
        raise Refusal(f'{program} --snapshot failed: {(result.stderr or result.stdout).strip()[:300]}')


def replace(target, data, mode, previous):
    """Write `data` to `target` atomically; copy a differing old file to `previous` first."""
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists() and target.read_bytes() == data:
        os.chmod(target, mode)
        return False
    handle, temporary = tempfile.mkstemp(prefix=f'.{target.name}-', dir=target.parent)
    try:
        with os.fdopen(handle, 'wb') as out:
            out.write(data)
        os.chmod(temporary, mode)
        if previous is not None and target.is_file():
            shutil.copy2(target, previous)
        os.replace(temporary, target)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    return True


def source_revision():
    result = subprocess.run(['git', '-C', str(REPO), 'describe', '--always', '--dirty', '--abbrev=12'],
                            capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else 'unknown (not a Git checkout)'


def install(binary=None):
    if binary is None:
        build = subprocess.run(['cargo', '+stable', 'build', '--locked', '--release'], cwd=REPO)
        if build.returncode:
            raise Refusal('the release build failed; nothing was installed.')
        binary = REPO / 'target/release/tinkery'
    binary = Path(binary).resolve()
    if not binary.is_file():
        raise Refusal(f'{binary} is not a file; nothing was installed.')
    snapshot(binary)
    home = Path.home()
    if not home.is_absolute():
        raise Refusal(f'HOME must be absolute, not {home}.')
    share = home / '.local/share/tinkery/bin'
    installed = share / 'tinkery'
    data = binary.read_bytes()
    replace(installed, data, 0o755, share / 'tinkery.previous')
    launcher = home / '.local/bin/tinkery'
    old_launcher = launcher.read_text(errors='replace') if launcher.is_file() else ''
    keep = share / 'launcher.previous' if old_launcher and MARKER not in old_launcher else None
    replace(launcher, launcher_text(installed).encode(), 0o755, keep)
    snapshot(launcher)
    print(f'Installed Tinkery {source_revision()} at {installed}')
    print(f'sha256 {hashlib.sha256(data).hexdigest()}')
    print(f'Launcher: {launcher}')
    if (share / 'tinkery.previous').is_file():
        print(f'The build before it: {share / "tinkery.previous"}')
    if keep is not None:
        print(f'The launcher this replaced: {keep}')
    on_path = shutil.which('tinkery')
    if on_path is None or Path(on_path).resolve() != launcher.resolve():
        print(f'{launcher.parent} is not first on PATH for `tinkery`; add: export PATH="$HOME/.local/bin:$PATH"')


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--binary', type=Path, help='install this built binary instead of building')
    args = parser.parse_args()
    try:
        install(args.binary)
    except Refusal as refusal:
        print(f'install refused: {refusal}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
